import java.awt.BasicStroke;
import java.awt.Color;
import java.awt.Graphics2D;
import java.awt.LinearGradientPaint;
import java.awt.RenderingHints;
import java.awt.Shape;
import java.awt.geom.AffineTransform;
import java.awt.geom.Arc2D;
import java.awt.geom.Ellipse2D;
import java.awt.geom.Path2D;
import java.awt.geom.Point2D;
import java.awt.geom.RoundRectangle2D;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;
import javax.imageio.ImageIO;

/**
 * Generates every SpendWise app icon from one geometry: a three-segment spending donut around a
 * rupee sign, on a deep indigo gradient. Coordinates use the 108x108 adaptive-icon grid.
 *
 * Run from the project root:  java tools/app-icon/AppIconGenerator.java
 */
public class AppIconGenerator {

    // Palette, from core/designsystem/theme/Color.kt.
    static final Color BG_TOP = new Color(0x2A2466);
    static final Color BG_BOTTOM = new Color(0x15122E);
    static final Color CYAN = new Color(0x00CEC9);
    static final Color ROSE = new Color(0xFD79A8);
    static final Color CHAMPAGNE = new Color(0xE8DCC6);
    static final Color GLYPH = Color.WHITE;

    static final double C = 54, RADIUS = 20.5, RING_WIDTH = 7.5, GLYPH_WIDTH = 3;

    /** Donut segments: start angle and end angle in degrees, clockwise from 3 o'clock. */
    record Segment(double start, double end, Color color) {}

    static final Segment[] SEGMENTS = {
        new Segment(-73, 52, CYAN),
        new Segment(86, 164, ROSE),
        new Segment(198, 253, CHAMPAGNE),
    };

    // Rupee sign: two bars, a bowl, and a diagonal leg.
    static final String RUPEE_BARS = "M47.2,44.6 L60.8,44.6 M47.2,50.2 L60.8,50.2";
    static final String RUPEE_BODY = "M49.3,44.6 C56.5,44.6 56.5,55.3 49.3,55.3 L60,63.4";

    public static void main(String[] args) throws IOException {
        Path root = Path.of(args.length > 0 ? args[0] : ".");
        Path res = root.resolve("androidApp/src/main/res");

        Files.writeString(res.resolve("drawable/ic_launcher_background.xml"), backgroundXml());
        Files.writeString(res.resolve("drawable/ic_launcher_foreground.xml"), foregroundXml(false));
        Files.writeString(res.resolve("drawable/ic_launcher_monochrome.xml"), foregroundXml(true));

        // Legacy launcher icons (Android 7.x, before adaptive icons).
        String[] densities = {"mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"};
        int[] sizes = {48, 72, 96, 144, 192};
        for (int i = 0; i < densities.length; i++) {
            Path dir = res.resolve("mipmap-" + densities[i]);
            Files.deleteIfExists(dir.resolve("ic_launcher.webp"));
            Files.deleteIfExists(dir.resolve("ic_launcher_round.webp"));
            write(render(sizes[i], Mask.ROUNDED_SQUARE), dir.resolve("ic_launcher.png"));
            write(render(sizes[i], Mask.CIRCLE), dir.resolve("ic_launcher_round.png"));
        }

        // Store artwork: square and opaque; Google Play and iOS apply their own corner masks.
        write(render(512, Mask.NONE), root.resolve("tools/app-icon/play-store-icon-512.png"));
        Path iosIcon = root.resolve("iosApp/iosApp/Assets.xcassets/AppIcon.appiconset");
        Files.createDirectories(iosIcon);
        write(render(1024, Mask.NONE), iosIcon.resolve("AppIcon-1024.png"));
        write(featureGraphic(root), root.resolve("tools/app-icon/play-feature-graphic-1024x500.png"));
        System.out.println("Icons and feature graphic written.");
    }

    // ---------------------------------------------------------------- Android vector drawables

    static String backgroundXml() {
        return """
            <?xml version="1.0" encoding="utf-8"?>
            <!-- Generated by tools/app-icon/AppIconGenerator.java. Edit the generator, not this file. -->
            <vector xmlns:android="http://schemas.android.com/apk/res/android"
                xmlns:aapt="http://schemas.android.com/aapt"
                android:width="108dp"
                android:height="108dp"
                android:viewportWidth="108"
                android:viewportHeight="108">
                <path android:pathData="M0,0h108v108h-108z">
                    <aapt:attr name="android:fillColor">
                        <gradient
                            android:type="linear"
                            android:startX="18" android:startY="0"
                            android:endX="90" android:endY="108"
                            android:startColor="%s"
                            android:endColor="%s" />
                    </aapt:attr>
                </path>
            </vector>
            """.formatted(hex(BG_TOP), hex(BG_BOTTOM));
    }

    static String foregroundXml(boolean monochrome) {
        StringBuilder paths = new StringBuilder();
        for (Segment s : SEGMENTS) {
            paths.append(strokePath(arcPathData(s), monochrome ? Color.WHITE : s.color(), RING_WIDTH));
        }
        Color glyph = monochrome ? Color.WHITE : GLYPH;
        paths.append(strokePath(RUPEE_BARS, glyph, GLYPH_WIDTH));
        paths.append(strokePath(RUPEE_BODY, glyph, GLYPH_WIDTH));
        return """
            <?xml version="1.0" encoding="utf-8"?>
            <!-- Generated by tools/app-icon/AppIconGenerator.java. Edit the generator, not this file. -->
            <vector xmlns:android="http://schemas.android.com/apk/res/android"
                android:width="108dp"
                android:height="108dp"
                android:viewportWidth="108"
                android:viewportHeight="108">
            %s</vector>
            """.formatted(paths);
    }

    static String strokePath(String data, Color color, double width) {
        return """
                <path
                    android:pathData="%s"
                    android:strokeColor="%s"
                    android:strokeWidth="%s"
                    android:strokeLineCap="round"
                    android:strokeLineJoin="round" />
            """.formatted(data, hex(color), num(width));
    }

    static String arcPathData(Segment s) {
        Point2D a = pointAt(s.start()), b = pointAt(s.end());
        int largeArc = (s.end() - s.start()) > 180 ? 1 : 0;
        return "M%s,%s A%s,%s 0 %d 1 %s,%s".formatted(
            num(a.getX()), num(a.getY()), num(RADIUS), num(RADIUS), largeArc, num(b.getX()), num(b.getY()));
    }

    static Point2D pointAt(double degrees) {
        double r = Math.toRadians(degrees);
        return new Point2D.Double(C + RADIUS * Math.cos(r), C + RADIUS * Math.sin(r));
    }

    // ---------------------------------------------------------------- Bitmap rendering

    enum Mask { NONE, ROUNDED_SQUARE, CIRCLE }

    /** Renders the visible 72x72 centre of the adaptive icon (18..90) into a size x size bitmap. */
    static BufferedImage render(int size, Mask mask) {
        boolean opaque = mask == Mask.NONE;
        BufferedImage image = new BufferedImage(size, size, opaque ? BufferedImage.TYPE_INT_RGB : BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = image.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);

        // Legacy icons get a small inset so the shape doesn't touch the edges, like system icons.
        double inset = mask == Mask.NONE ? 0 : size * 0.04;
        double box = size - 2 * inset;
        Shape clip = switch (mask) {
            case NONE -> null;
            case ROUNDED_SQUARE -> new RoundRectangle2D.Double(inset, inset, box, box, box * 0.36, box * 0.36);
            case CIRCLE -> new Ellipse2D.Double(inset, inset, box, box);
        };
        if (clip != null) g.setClip(clip);

        AffineTransform grid = new AffineTransform();
        grid.translate(inset, inset);
        grid.scale(box / 72.0, box / 72.0);
        grid.translate(-18, -18);
        g.transform(grid);

        g.setPaint(new LinearGradientPaint(18, 0, 90, 108, new float[] {0f, 1f}, new Color[] {BG_TOP, BG_BOTTOM}));
        g.fill(new java.awt.geom.Rectangle2D.Double(0, 0, 108, 108));
        drawMark(g);
        g.dispose();
        return image;
    }

    /** Draws the donut and rupee sign; [g] must already be transformed to the 108x108 grid. */
    static void drawMark(Graphics2D g) {
        g.setStroke(new BasicStroke((float) RING_WIDTH, BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND));
        for (Segment s : SEGMENTS) {
            g.setColor(s.color());
            // Arc2D measures angles counter-clockwise; our grid angles are clockwise.
            g.draw(new Arc2D.Double(C - RADIUS, C - RADIUS, 2 * RADIUS, 2 * RADIUS, -s.start(), -(s.end() - s.start()), Arc2D.OPEN));
        }

        g.setColor(GLYPH);
        g.setStroke(new BasicStroke((float) GLYPH_WIDTH, BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND));
        g.draw(parse(RUPEE_BARS));
        g.draw(parse(RUPEE_BODY));
    }

    // ---------------------------------------------------------------- Play Store feature graphic

    static final String TITLE = "SpendWise";
    static final String TAGLINE = "Every rupee, at a glance.";
    static final String DETAILS = "Quick logging  ·  Works offline  ·  Cloud sync";

    /** 1024x500 opaque banner: the mark beside the name and tagline, on the icon's indigo with aurora glows. */
    static BufferedImage featureGraphic(Path root) throws IOException {
        int w = 1024, h = 500;
        BufferedImage image = new BufferedImage(w, h, BufferedImage.TYPE_INT_RGB);
        Graphics2D g = image.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
        g.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_FRACTIONALMETRICS, RenderingHints.VALUE_FRACTIONALMETRICS_ON);

        g.setPaint(new LinearGradientPaint(0, 0, w, h, new float[] {0f, 1f}, new Color[] {BG_TOP, BG_BOTTOM}));
        g.fillRect(0, 0, w, h);
        glow(g, 170, 90, 420, new Color(0x6C5CE7), 0.55f);
        glow(g, 990, 520, 440, CYAN, 0.22f);
        glow(g, 760, -60, 340, ROSE, 0.20f);

        Path fonts = root.resolve("shared/src/commonMain/composeResources/font");
        java.awt.Font title = font(fonts.resolve("fraunces_semibold.ttf"), 92f);
        java.awt.Font tagline = font(fonts.resolve("inter_medium.ttf"), 32f);
        java.awt.Font details = font(fonts.resolve("inter_regular.ttf"), 21f);

        // Lay out mark + gap + text as one group, centred horizontally.
        double scale = 5.4;
        double markRadius = (RADIUS + RING_WIDTH / 2) * scale;
        double gap = 56;
        double textWidth = Math.max(width(g, title, TITLE), Math.max(width(g, tagline, TAGLINE), width(g, details, DETAILS)));
        double left = (w - (2 * markRadius + gap + textWidth)) / 2;
        double cy = h / 2.0;

        AffineTransform saved = g.getTransform();
        g.translate(left + markRadius, cy);
        g.scale(scale, scale);
        g.translate(-C, -C);
        drawMark(g);
        g.setTransform(saved);

        float x = (float) (left + 2 * markRadius + gap);
        g.setFont(title);
        g.setColor(Color.WHITE);
        g.drawString(TITLE, x, (float) cy - 12);
        g.setFont(tagline);
        g.setColor(CHAMPAGNE);
        g.drawString(TAGLINE, x, (float) cy + 44);
        g.setFont(details);
        g.setColor(new Color(255, 255, 255, 150));
        g.drawString(DETAILS, x, (float) cy + 94);
        g.dispose();
        return image;
    }

    static void glow(Graphics2D g, float x, float y, float radius, Color color, float alpha) {
        Color center = new Color(color.getRed(), color.getGreen(), color.getBlue(), Math.round(alpha * 255));
        Color edge = new Color(color.getRed(), color.getGreen(), color.getBlue(), 0);
        g.setPaint(new java.awt.RadialGradientPaint(x, y, radius, new float[] {0f, 1f}, new Color[] {center, edge}));
        g.fill(new Ellipse2D.Float(x - radius, y - radius, 2 * radius, 2 * radius));
    }

    static java.awt.Font font(Path file, float size) throws IOException {
        try {
            return java.awt.Font.createFont(java.awt.Font.TRUETYPE_FONT, file.toFile()).deriveFont(size);
        } catch (java.awt.FontFormatException e) {
            throw new IOException("Can't read font " + file, e);
        }
    }

    static double width(Graphics2D g, java.awt.Font font, String text) {
        return g.getFontMetrics(font).getStringBounds(text, g).getWidth();
    }

    /** Minimal SVG path parser: absolute M, L and C commands only. */
    static Path2D parse(String data) {
        Path2D path = new Path2D.Double();
        String[] tokens = data.replace(",", " ").trim().split("\\s+|(?=[MLC])|(?<=[MLC])");
        char command = 'M';
        int i = 0;
        while (i < tokens.length) {
            String t = tokens[i];
            if (t.isEmpty()) { i++; continue; }
            if (Character.isLetter(t.charAt(0))) { command = t.charAt(0); i++; continue; }
            double[] v = new double[command == 'C' ? 6 : 2];
            for (int k = 0; k < v.length; k++) v[k] = Double.parseDouble(tokens[i++]);
            switch (command) {
                case 'M' -> path.moveTo(v[0], v[1]);
                case 'L' -> path.lineTo(v[0], v[1]);
                case 'C' -> path.curveTo(v[0], v[1], v[2], v[3], v[4], v[5]);
                default -> throw new IllegalArgumentException("Unsupported path command " + command);
            }
        }
        return path;
    }

    static void write(BufferedImage image, Path file) throws IOException {
        Files.createDirectories(file.getParent());
        ImageIO.write(image, "png", new File(file.toString()));
    }

    static String hex(Color c) {
        return String.format("#%02X%02X%02X", c.getRed(), c.getGreen(), c.getBlue());
    }

    static String num(double v) {
        String s = String.format(Locale.ROOT, "%.2f", v);
        return s.contains(".") ? s.replaceAll("0+$", "").replaceAll("\\.$", "") : s;
    }
}
