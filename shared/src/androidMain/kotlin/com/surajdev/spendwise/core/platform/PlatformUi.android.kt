actual val platformName: String = "Android ${Build.VERSION.RELEASE}"

@Composable
actual fun rememberSocialSignInLauncher(): SocialSignInLauncher {
    val context = LocalContext.current
    return remember(context) { AndroidSocialSignInLauncher(context) }
}

private class AndroidSocialSignInLauncher(private val context: Context) : SocialSignInLauncher {

    /** Generated by the google-services plugin from google-services.json. */
    private val webClientId: String? = context.resources
        .getIdentifier("default_web_client_id", "string", context.packageName)
        .takeIf { it != 0 }
        ?.let(context::getString)

    override val supportsGoogle: Boolean = webClientId != null

    // Sign in with Apple is only required (and only offered) on iOS.
    override val supportsApple: Boolean = false

    override suspend fun signInWithGoogle(): SocialSignInResult {
        val clientId = webClientId ?: return SocialSignInResult.Failed("Google sign-in isn't configured.")
        val activity = context.findActivity() ?: return SocialSignInResult.Failed("Couldn't open Google sign-in.")
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(clientId).build())
            .build()
        return try {
            val credential = CredentialManager.create(activity).getCredential(activity, request).credential
            if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                SocialSignInResult.Google(GoogleIdTokenCredential.createFrom(credential.data).idToken, accessToken = null)
            } else {
                SocialSignInResult.Failed("Unexpected credential type.")
            }
        } catch (e: GetCredentialCancellationException) {
            SocialSignInResult.Cancelled
        } catch (e: NoCredentialException) {
            SocialSignInResult.Failed("No Google account found on this device.")
        } catch (e: GetCredentialException) {
            SocialSignInResult.Failed(e.message ?: "Google sign-in failed.")
        }
    }

    override suspend fun signInWithApple(): SocialSignInResult =
        SocialSignInResult.Failed("Sign in with Apple is available on iPhone.")
}

@Composable
actual fun rememberNotificationPermissionRequester(onResult: (granted: Boolean) -> Unit): () -> Unit {
    val context = LocalContext.current
    val launcher = rememberLauncherForActivityResult(ActivityResultContracts.RequestPermission(), onResult)
    return remember(context, launcher) {
        {
            if (Build.VERSION.SDK_INT < Build.VERSION_CODES.TIRAMISU ||
                ContextCompat.checkSelfPermission(context, Manifest.permission.POST_NOTIFICATIONS) == PackageManager.PERMISSION_GRANTED
            ) {
                onResult(true)
            } else {
                launcher.launch(Manifest.permission.POST_NOTIFICATIONS)
            }
        }
    }
}

@Composable
actual fun SystemBarsEffect(darkTheme: Boolean) {
    val view = LocalView.current
    if (view.isInEditMode) return
    SideEffect {
        val window = view.context.findActivity()?.window ?: return@SideEffect
        WindowCompat.getInsetsController(window, view).apply {
            isAppearanceLightStatusBars = !darkTheme
            isAppearanceLightNavigationBars = !darkTheme
        }
    }
}

private tailrec fun Context.findActivity(): Activity? = when (this) {
    is Activity -> this
    is ContextWrapper -> baseContext.findActivity()
    else -> null
}
